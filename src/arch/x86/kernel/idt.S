.extern irq_global_handler 

irq_stub:
    pushq %fs
    pushq %gs
    PUSHAQ

    lea (%rsp), %rdi    # load struct irq_frame * as the first parameter to irq_global_handler 
    call irq_global_handler 

irq_stub_end: 
    POPAQ 
    popq %gs
    popq %fs
    addq $0x10, %rsp       # Remove the pushed irq_number and the err_code from the stack to allow the CPU to perform an IRET
    iretq

.macro irq num
irq_stub_\num:
    .if (\num != 8) && ((\num < 10) || (\num > 14))
        pushq $0
    .endif
    pushq $\num
    jmp irq_stub
.endm

