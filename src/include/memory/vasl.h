
#ifndef VASL_H
#define VASL_H

#define VASL_VIRTUAL_BASE           0xffffffff80000000 
#define VASL_KERNEL_BASE            VASL_VIRTUAL_BASE + 0x10000000 
#define VASL_KERNEL_STACK_BOTTOM    VASL_KERNEL_BASE + 0xB0000000
#define VASL_KERNEL_STACK_TOP       VASL_KERNEL_BASE + 0xC0000000
#define VASL_KERNEL_PHYS_OFFSET     VASL_KERNEL_BASE + 0xD0000000

#define V2P(x) ((x) - VASL_VIRTUAL_BASE)
#define VGETPML(x)  (x & PML4_IDX_MASK)
#define VGETPDPT(x) (x & PDPT_IDX_MASK)
#define VGETPDT(x)  (x & PDT_IDX_MASK)

#define VASL_USER_EXEC_BASE         0x00007FF000000000
#define VASL_USER_HEAP_BASE         0x00007FF00C000000

#endif // VASL_H